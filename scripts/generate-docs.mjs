// Writes agent-facing reference docs from the catalog definition, so they
// cannot drift from what the renderer accepts. Run after building @surfaces-ui/spec.
import fs from "node:fs";
import path from "node:path";
import { SITE_COMPONENT_NAMES, analyticsCatalog, basicsCatalog, catalogDocs, catalogJson, catalogPrompt, patternDocs, siteCatalog } from "../packages/spec/dist/index.js";

const out = path.resolve("docs/catalog");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, "components"), { recursive: true });

const docs = catalogDocs(analyticsCatalog);
for (const [name, markdown] of Object.entries(docs)) fs.writeFileSync(path.join(out, "components", `${name}.md`), markdown);
fs.writeFileSync(path.join(out, "catalog.json"), `${JSON.stringify(catalogJson(analyticsCatalog), null, 2)}\n`);
fs.writeFileSync(path.join(out, "agent-prompt.md"), catalogPrompt(analyticsCatalog));
fs.writeFileSync(path.join(out, "patterns.md"), patternDocs());
fs.writeFileSync(
  path.join(out, "README.md"),
  [
    `# ${analyticsCatalog.title} catalog`,
    "",
    analyticsCatalog.description,
    "",
    `Catalog ID: \`${analyticsCatalog.id}\``,
    "",
    "Generated by `pnpm docs:gen` from `packages/spec/src/analytics.ts`. Do not edit by hand.",
    "",
    "- [agent-prompt.md](agent-prompt.md): instructions that teach an agent to build UI with this catalog",
    "- [catalog.json](catalog.json): the catalog as an A2UI catalog document (JSON Schema)",
    "- [patterns.md](patterns.md): surfaces for the moments a person must decide (connecting, cleaning, personal data, transformations)",
    "- [site/](site/README.md): the site catalog, for pages people read (landing pages, docs, posts), built on the same basic components",
    "",
    "## Components",
    "",
    ...Object.keys(docs).map((name) => `- [${name}](components/${name}.md): ${analyticsCatalog.components[name].description}`),
    "",
  ].join("\n"),
);
console.log(`Wrote ${Object.keys(docs).length} component docs to ${path.relative(process.cwd(), out)}`);

// The site catalog: the basics (documented above, under components/) and the components a site adds.
const siteOut = path.join(out, "site");
fs.mkdirSync(path.join(siteOut, "components"), { recursive: true });
const siteDocs = catalogDocs(siteCatalog, { markup: "siteMarkup" });
for (const name of SITE_COMPONENT_NAMES) fs.writeFileSync(path.join(siteOut, "components", `${name}.md`), siteDocs[name]);
fs.writeFileSync(path.join(siteOut, "catalog.json"), `${JSON.stringify(catalogJson(siteCatalog), null, 2)}\n`);
fs.writeFileSync(path.join(siteOut, "agent-prompt.md"), catalogPrompt(siteCatalog));
fs.writeFileSync(
  path.join(siteOut, "README.md"),
  [
    `# ${siteCatalog.title} catalog`,
    "",
    siteCatalog.description,
    "",
    `Catalog ID: \`${siteCatalog.id}\``,
    "",
    "Generated by `pnpm docs:gen` from `packages/spec/src/site.ts` and `packages/spec/src/basics.ts`. Do not edit by hand.",
    "",
    "- [agent-prompt.md](agent-prompt.md): instructions that teach an agent to build pages with this catalog",
    "- [catalog.json](catalog.json): the catalog as an A2UI catalog document (JSON Schema)",
    "",
    "## Components a site adds",
    "",
    ...SITE_COMPONENT_NAMES.map((name) => `- [${name}](components/${name}.md): ${siteCatalog.components[name].description}`),
    "",
    "## The basics",
    "",
    "Shared with the analytics catalog, and documented there.",
    "",
    ...basicsCatalog.names.map((name) => `- [${name}](../components/${name}.md): ${basicsCatalog.components[name].description}`),
    "",
  ].join("\n"),
);
console.log(`Wrote ${SITE_COMPONENT_NAMES.length} site component docs to ${path.relative(process.cwd(), siteOut)}`);

// App components: the components an app places itself, described in each
// package's appComponents.ts. Only the descriptions are loaded, not React.
const { appComponentMarkdown, componentsAppComponents } = await import("../packages/components/dist/appComponents.js");
const { chatAppComponents } = await import("../packages/chat/dist/appComponents.js");
const appOut = path.resolve("docs/components");
fs.rmSync(appOut, { recursive: true, force: true });
fs.mkdirSync(appOut, { recursive: true });
const { appComponentDocs: devtoolsAppComponents } = await import("../packages/devtools/dist/appComponents.js");
const appDocs = [...chatAppComponents, ...componentsAppComponents, ...devtoolsAppComponents];
for (const doc of appDocs) fs.writeFileSync(path.join(appOut, `${doc.name}.md`), appComponentMarkdown(doc));
fs.writeFileSync(
  path.join(appOut, "README.md"),
  [
    "# App components",
    "",
    "Components an app places itself, beside the catalog's, which an agent draws ([docs/catalog](../catalog/README.md)). Each page lists the props that are plain data, the parts a host supplies in code, its callbacks and an example. The playground's Components area draws each live under App components.",
    "",
    "Generated by `pnpm docs:gen` from `appComponents.ts` in `packages/chat`, `packages/components` and `packages/devtools`. Do not edit by hand.",
    "",
    ...appDocs.map((doc) => `- [${doc.name}](${doc.name}.md) (\`${doc.from}\`): ${doc.description.split(". ")[0].replace(/\.$/, "")}.`),
    "",
  ].join("\n"),
);
console.log(`Wrote ${appDocs.length} app component docs to ${path.relative(process.cwd(), appOut)}`);

// Recipes: prose from apps/recipes/src/<name>/recipe.md, with each
// `{{file: x}}` line replaced by that tested source file.
const recipesIn = path.resolve("apps/recipes/src");
const recipesOut = path.resolve("docs/recipes");
fs.rmSync(recipesOut, { recursive: true, force: true });
fs.mkdirSync(recipesOut, { recursive: true });
const fence = { ts: "ts", tsx: "tsx", js: "js", mjs: "js", json: "json", sql: "sql", sh: "bash", html: "html", css: "css" };
const recipes = [];
for (const name of fs.existsSync(recipesIn) ? fs.readdirSync(recipesIn).sort() : []) {
  const dir = path.join(recipesIn, name);
  const source = path.join(dir, "recipe.md");
  if (!fs.existsSync(source)) continue;
  const text = fs.readFileSync(source, "utf8").replace(/^\{\{file:\s*([^}]+?)\s*\}\}$/gm, (_, file) => {
    const full = path.join(dir, file);
    if (!fs.existsSync(full)) throw new Error(`${name}/recipe.md includes ${file}, which does not exist`);
    const code = fs.readFileSync(full, "utf8").trimEnd();
    return [`\`${file}\`:`, "", `\`\`\`${fence[path.extname(file).slice(1)] ?? ""}`, code, "```"].join("\n");
  });
  const title = /^#\s+(.+)$/m.exec(text)?.[1] ?? name;
  const summary = text.split("\n").find((line, i, all) => i > all.findIndex((l) => l.startsWith("# ")) && line.trim() && !line.startsWith("#")) ?? "";
  fs.writeFileSync(path.join(recipesOut, `${name}.md`), `<!-- Generated by pnpm docs:gen from apps/recipes/src/${name}. Do not edit by hand. -->\n\n${text.trimEnd()}\n\nSource and test: [apps/recipes/src/${name}](../../apps/recipes/src/${name})\n`);
  recipes.push({ name, title, summary });
}
fs.writeFileSync(
  path.join(recipesOut, "README.md"),
  [
    "# Recipes",
    "",
    "Each recipe is code that runs in CI: the source shown is the source tested in `apps/recipes`. Generated by `pnpm docs:gen`; do not edit by hand.",
    "",
    ...recipes.map((r) => `- [${r.title}](${r.name}.md): ${r.summary}`),
    "",
  ].join("\n"),
);
console.log(`Wrote ${recipes.length} recipes to ${path.relative(process.cwd(), recipesOut)}`);
