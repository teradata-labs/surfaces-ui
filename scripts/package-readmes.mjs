function readme(dir, pkg) {
  const note = NOTES[pkg.name] ?? {};
  const peers = Object.keys(pkg.peerDependencies ?? {});
  const lines = [MARK, "", `# ${pkg.name}`, "", pkg.description.endsWith(".") ? pkg.description : `${pkg.description}.`, ""];
  if (note.about) lines.push(note.about, "");
  if (note.install !== false) {
    lines.push("## Install", "", "```bash", `npm install ${[pkg.name, ...peers].join(" ")}`, "```", "");
    if (peers.length > 0) lines.push(`${peers.map((p) => `\`${p}\``).join(" and ")} ${peers.length === 1 ? "is a peer dependency" : "are peer dependencies"}: your app provides ${peers.length === 1 ? "it" : "them"}.`, "");
  }
  if (note.example) lines.push(note.install === false ? "## Start" : "## Use", "", `\`\`\`${note.lang ?? "tsx"}`, note.example, "```", "");
  if (note.after) lines.push(note.after, "");
  lines.push(
    "## Part of Surfaces UI",
    "",
    "Surfaces UI is a UI library for data and analytics: exploring schemas, querying, charting, tables at scale, chat, and pages an agent can build.",
    "",
    "Every Surfaces UI package is released at the same version; install them all at that one version, since mixing releases is not supported.",
    "",
    "- [The guides on surfaces-ui.com](https://surfaces-ui.com/#docs)",
    `- [Getting started](${REPO}/blob/main/docs/getting-started.md)`,
    `- [Building with an agent](${REPO}/blob/main/docs/agent-integration.md)`,
    `- [Styling](${REPO}/blob/main/docs/styling.md)`,
    `- [Source for this package](${REPO}/tree/main/${dir})`,
    "",
    `Licensed under ${pkg.license}. See LICENSE and NOTICE.`,
    "",
  );
  return lines.join("\n");
}

