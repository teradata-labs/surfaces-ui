/** Third-party packages under one family name, so a row says "CodeMirror" once rather than eight times. */
const FAMILIES = [
  [/^@codemirror\/|^@lezer\//, "CodeMirror"],
  [/^@modelcontextprotocol\//, "MCP SDK"],
  [/^@connectrpc\//, "Connect"],
  [/^@bufbuild\/protobuf$/, "protobuf-es"],
  [/^apache-arrow$/, "Apache Arrow"],
  [/^@duckdb\/node-bindings$|^@apache-arrow\/adbc-driver-manager$/, "DuckDB (native, through ADBC)"],
  [/^@huggingface\/transformers$/, "Transformers.js"],
];
const family = (name) => FAMILIES.find(([pattern]) => pattern.test(name))?.[1] ?? name;
const unique = (list) => [...new Set(list)];

function overview(packages) {
  const byName = new Map(packages.map((p) => [p.pkg.name, p]));
  const grouped = GROUPS.flatMap((g) => g.packages);
  const missing = [...byName.keys()].filter((name) => !grouped.includes(name));
  const unknown = grouped.filter((name) => !byName.has(name));
  if (missing.length || unknown.length) {
    throw new Error(`docs/packages.md: put every published package in one group of GROUPS in scripts/package-readmes.mjs (missing: ${missing.join(", ") || "none"}; not a package: ${unknown.join(", ") || "none"})`);
  }
  // A table cell: backslashes first, so a pipe's escape cannot be undone by one already in the text.
  const first = (text) => (/^(.+?\.)(\s|$)/.exec(text)?.[1] ?? text).replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
  const lines = [
    "<!-- Generated by scripts/package-readmes.mjs from each package.json. Edit the script, not this file. -->",
    "",
    "# Packages",
    "",
    `Surfaces UI is ${packages.length} packages on npm, released together at one version, so any two of them always work together. Most apps install two to six of them; the rest come along as dependencies, or are parts of the server.`,
    "",
    "## What an app installs",
    "",
    "| You want | Install |",
    "|---|---|",
    "| Components over your own backend (grid, chart, pivot, editor, explorers, forms) | `@surfaces-ui/components` `@surfaces-ui/data` |",
    "| Pages and views an agent describes | add `@surfaces-ui/spec` |",
    "| A chat thread with an agent | add `@surfaces-ui/chat`, and an agent backend |",
    "| The reference server (DuckDB, Teradata, DataFusion) | `@surfaces-ui/client-connect` in the app, `@surfaces-ui/dev-server` beside it |",
    "| SQL in the browser with no server | `@surfaces-ui/datasource-duckdb-wasm` and `@duckdb/duckdb-wasm` |",
    "| All of it, set up | `npx create-surfaces my-app` |",
    "",
    "React 18 or 19 is a peer of every package that draws: your app provides it.",
    "",
    "Each package below links to its own README, with how to install and use it. \"Brings\" lists the other Surfaces UI packages a package depends on directly, and its larger third-party dependencies; peers are what your app provides.",
    "",
  ];
  for (const group of GROUPS) {
    lines.push(`## ${group.title}`, "", group.intro, "", "| Package | What it is | Brings | Peers |", "|---|---|---|---|");
    for (const name of group.packages) {
      const { dir, pkg } = byName.get(name);
      const deps = Object.keys(pkg.dependencies ?? {});
      const ours = deps.filter((d) => d.startsWith("@surfaces-ui/")).map((d) => `\`${d.replace("@surfaces-ui/", "")}\``);
      const theirs = unique(deps.filter((d) => !d.startsWith("@surfaces-ui/")).map(family));
      const brings = [...ours, ...theirs].join(", ") || "nothing";
      const peers = Object.keys(pkg.peerDependencies ?? {}).map((p) => `\`${p}\`${pkg.peerDependenciesMeta?.[p]?.optional ? " (optional)" : ""}`).join(", ") || "none";
      const about = first(NOTES[name]?.about ?? pkg.description);
      lines.push(`| [\`${name}\`](../${dir}/README.md) | ${about} | ${brings} | ${peers} |`);
    }
    lines.push("");
  }
  lines.push(
    "## Worth knowing",
    "",
    "- **The data layer is optional.** `components`, `spec`, `chat` and the other packages that draw depend only on the `DataSource` interface in `@surfaces-ui/data`, never on an engine, a driver, a Connect client or the server (`pnpm check:boundaries` holds this). An app on its own backend implements `DataSource` and installs nothing from the server side.",
    "- **`@surfaces-ui/dev-server` brings every engine.** It depends on the DuckDB, Teradata and DataFusion adapters, the pipeline runner and dbt support, so a server that only reads Teradata still installs DuckDB's native library.",
    "- **No Teradata driver is installed.** `@surfaces-ui/engine-teradata` talks to Teradata Query Service over `fetch`, or to a driver connection your server opens with a driver you install yourself.",
    "- **Before the first release (0.2.0), each package was checked on its own**: packed as npm publishes it, installed alone into an empty project, and every JavaScript entry imported; the app `create-surfaces` writes was then installed from those packages, built, and its data server started and answered. Releasing is described in [releasing.md](releasing.md).",
    "",
  );
  return lines.join("\n");
}

const check = process.argv.includes("--check");
const stale = [];
const published = [];
for (const name of fs.readdirSync(path.join(root, "packages"))) {
  const dir = `packages/${name}`;
  const file = path.join(root, dir, "package.json");
  if (!fs.existsSync(file)) continue;
  const pkg = JSON.parse(fs.readFileSync(file, "utf8"));
  if (pkg.private) continue;
  published.push({ dir, pkg });
  const target = path.join(root, dir, "README.md");
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : undefined;
  if (current?.includes(OWN)) continue;
  const next = readme(dir, pkg);
  if (current === next) continue;
  if (check) stale.push(dir);
  else fs.writeFileSync(target, next);
}
{
  const target = path.join(root, "docs", "packages.md");
  const next = overview(published);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : undefined;
  if (current !== next) {
    if (check) stale.push("docs/packages.md");
    else fs.writeFileSync(target, next);
  }
}
if (stale.length > 0) {
  console.error(`READMEs missing or stale (run node scripts/package-readmes.mjs):\n${stale.map((d) => `  - ${d}`).join("\n")}`);
  process.exit(1);
}
