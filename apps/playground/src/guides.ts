/**
 * The guides: the Markdown files in `docs/` shown on the site, read by the Docs page in the browser and by the build,
 * which writes each one as a page of its own. Plain functions over paths and text, so both read the same rules.
 */

/** Which files under `docs/` are guides (paths relative to `docs/`). The plan is for this repository's own work. */
export function isGuideFile(path: string): boolean {
  if (path === "plan.md" || !path.endsWith(".md")) return false;
  return /^[^/]+\.md$/.test(path) || /^(recipes|components)\/[^/]+\.md$/.test(path) || path === "catalog/patterns.md";
}

/** A guide's id is its path under `docs/` without `.md` (`recipes/analytics-chat`). */
export const guideId = (path: string) => path.replace(/\.md$/, "");

/** The guides a reader starts with, in reading order. */
export const START = ["getting-started", "packages", "agent-integration", "styling", "accessibility"];

const TITLES: Record<string, string> = {
  "getting-started": "Getting started",
  packages: "Packages",
  "agent-integration": "Agent integration",
  styling: "Styling",
  accessibility: "Accessibility",
  "recipes/README": "All recipes",
  "components/README": "All app components",
  "catalog/patterns": "Human-in-the-loop patterns",
};

/** A guide's title: a name given above, or its first heading. */
export const guideTitle = (id: string, text: string | undefined) => TITLES[id] ?? /^#\s+(.+)$/m.exec(text ?? "")?.[1]?.replace(/[`*]/g, "").trim() ?? id;

/**
 * A guide's text as it is shown: a note left for whoever edits the file (`<!-- Generated by … -->`) is not part of it.
 * Removed until none is left, so text that would rejoin into a note once one is taken out cannot leave one behind. The
 * text is drawn by `Markdown`, which never reads it as HTML; this only keeps editors' notes out of what people read.
 */
export function guideText(text: string): string {
  let shown = text;
  for (let before = ""; before !== shown; ) {
    before = shown;
    shown = shown.replace(/<!--[\s\S]*?-->\s*/g, "");
  }
  return shown;
}

/** The first paragraph of prose in a guide, for its description in search results and link previews. */
export function guideSummary(text: string, limit = 160): string {
  const paragraph =
    guideText(text)
      .replace(/```[\s\S]*?```/g, "")
      .split(/\n\s*\n/)
      .map((block) => block.trim())
      .find((block) => block && !/^(#|\||[-*+] |\d+\. |>|<|!\[)/.test(block)) ?? "";
  const plain = paragraph
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/[`*_]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (plain.length <= limit) return plain;
  const cut = plain.slice(0, limit - 1);
  return `${cut.slice(0, cut.lastIndexOf(" ") > 80 ? cut.lastIndexOf(" ") : cut.length)}…`;
}

export const REPO = "https://github.com/teradata-labs/surfaces-ui/blob/main/";

/**
 * Where a link in a guide goes: another guide or a catalog component on this site (as a target such as
 * `docs?page=styling`), or the file in the repository. An anchor on the same page is left as it is (undefined).
 */
export function guideLink(from: string, href: string, hasGuide: (id: string) => boolean): { target: string } | { url: string } | undefined {
  if (href.startsWith("#")) return undefined;
  const base = new URL(`https://docs.invalid/docs/${from}`);
  const url = new URL(href, base);
  if (url.origin !== base.origin) return undefined;
  const path = decodeURIComponent(url.pathname.slice(1));
  const component = /^docs\/catalog\/components\/(\w+)\.md$/.exec(path);
  if (component) return { target: `catalog?component=${component[1]}` };
  if (/^docs\/catalog\/components\/?$/.test(path)) return { target: "catalog" };
  const guide = /^docs\/(.+)\.md$/.exec(path)?.[1];
  if (guide && hasGuide(guide)) return { target: `docs?page=${guide}` };
  if (/^docs\/(recipes|components)\/?$/.test(path)) return { target: `docs?page=${path.slice(5).replace(/\/$/, "")}/README` };
  return { url: `${REPO}${path}` };
}

export interface Guide {
  id: string;
  title: string;
}

/** The sections of the guide list, in reading order. Anything not named in `START` is listed under its folder by name. */
export function guideSections(ids: string[], titleOf: (id: string) => string): { label: string; guides: Guide[] }[] {
  const list = (pick: (id: string) => boolean) =>
    ids
      .filter(pick)
      .sort((a, b) => Number(b.endsWith("README")) - Number(a.endsWith("README")) || a.localeCompare(b))
      .map((id) => ({ id, title: titleOf(id) }));
  return [
    { label: "Start here", guides: START.filter((id) => ids.includes(id)).map((id) => ({ id, title: titleOf(id) })) },
    { label: "Recipes", guides: list((id) => id.startsWith("recipes/")) },
    { label: "App components", guides: list((id) => id.startsWith("components/")) },
    { label: "Patterns", guides: list((id) => id.startsWith("catalog/")) },
    { label: "More", guides: list((id) => !id.includes("/") && !START.includes(id)) },
  ].filter((section) => section.guides.length > 0);
}
